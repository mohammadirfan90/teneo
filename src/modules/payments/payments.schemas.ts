// src/modules/payments/payments.schemas.ts
//
// Zod schemas for /api/v1/payments body / query / params inputs.
//
// Names match the route path so they're easy to grep from the
// controller. Zod enum tuples duplicate Prisma enum values so the
// inferred types stay narrow (see leases.schemas.ts for rationale).

import { z } from 'zod';

import type {
  PaymentStatus as PaymentStatusEnum,
  PaymentGateway as PaymentGatewayEnum,
} from '@/generated/prisma/enums';

// ──────────────────────────────────────────────────────────────────────
// Enums (mirror Prisma enum values exactly — kept in sync via tests).
// ──────────────────────────────────────────────────────────────────────

const paymentStatusValues = [
  'PROCESSING',
  'SUCCEEDED',
  'FAILED',
  'REFUNDED',
] as const satisfies readonly PaymentStatusEnum[];

const paymentGatewayValues = [
  'STRIPE',
] as const satisfies readonly PaymentGatewayEnum[];

// ──────────────────────────────────────────────────────────────────────
// Params schemas
// ──────────────────────────────────────────────────────────────────────

export const paymentIdParamsSchema = z.object({
  id: z.string().uuid({ message: 'payment id must be a UUID' }),
});
export type PaymentIdParams = z.infer<typeof paymentIdParamsSchema>;

// ──────────────────────────────────────────────────────────────────────
// Body schemas
// ──────────────────────────────────────────────────────────────────────

/**
 * POST /payments/stripe/intent — body needs invoiceId + idempotencyKey.
 *
 * `idempotencyKey` is caller-supplied (typically a UUID generated by
 * the client). The DB enforces uniqueness on retry via the
 * `payments_idempotency_key_uq` partial-unique index; the
 * `withIdempotency` middleware caches the response envelope for 24h
 * (belt-and-braces).
 *
 * Constraint: `idempotencyKey` MUST be a stable client-side identifier
 * — we do NOT derive it server-side. This lets the client retry on
 * network blips and always see the same `paymentId` + `clientSecret`.
 */
export const intentSchema = z
  .object({
    invoiceId: z.string().uuid({ message: 'invoiceId must be a UUID' }),
    idempotencyKey: z
      .string()
      .min(1, 'idempotencyKey must not be empty')
      .max(255, 'idempotencyKey must be at most 255 characters'),
  })
  .strict();
export type IntentInput = z.infer<typeof intentSchema>;

/**
 * POST /payments/:id/refund — body requires a non-empty reason for
 * audit. ADMIN only. The refund amount is implicit (full payment —
 * partial refunds are deferred to Phase 18+).
 *
 * Constraint: the field name MUST be `reason` to match the audit log
 * shape used by other modules.
 */
export const refundPaymentSchema = z
  .object({
    reason: z
      .string()
      .min(1, 'reason must not be empty')
      .max(1000, 'reason must be at most 1000 characters'),
  })
  .strict();
export type RefundPaymentInput = z.infer<typeof refundPaymentSchema>;

// ──────────────────────────────────────────────────────────────────────
// Cursor query schema for GET /payments/me
// ──────────────────────────────────────────────────────────────────────

export const paymentListQuerySchema = z.object({
  limit: z.coerce.number().int().min(1).max(100).optional().default(20),
  cursor: z.string().min(1).max(1024).optional(),
});
export type PaymentListQuery = z.infer<typeof paymentListQuerySchema>;

// ──────────────────────────────────────────────────────────────────────
// Re-export enum tuples for callers that don't want to re-import.
// ──────────────────────────────────────────────────────────────────────
export { paymentStatusValues, paymentGatewayValues };

// ──────────────────────────────────────────────────────────────────────
// View shapes (returned in the response envelope's `data` field).
// These mirror the row shapes after the service layer has denormalized
// BigInt → string for JSON safety.
// ──────────────────────────────────────────────────────────────────────

/** Full view — used by GET /payments/:id, POST /payments/stripe/intent,
 *  POST /payments/:id/refund. */
export interface PaymentView {
  id: string;
  invoiceId: string;
  leaseId: string;
  tenantUserId: string;
  gateway: string;
  gatewayPaymentIntentId: string | null;
  gatewayChargeId: string | null;
  gatewayRefundId: string | null;
  amountMinor: string;
  refundedAmountMinor: string;
  currency: string;
  status: string;
  idempotencyKey: string;
  failureCode: string | null;
  failureReason: string | null;
  cancellationReason: string | null;
  paidAt: string | null;
  failedAt: string | null;
  refundedAt: string | null;
  canceledAt: string | null;
  version: number;
  createdAt: string;
  updatedAt: string;
}

/** Summary view — used by GET /payments/me cursor pagination. */
export interface PaymentSummaryView {
  id: string;
  invoiceId: string;
  amountMinor: string;
  refundedAmountMinor: string;
  currency: string;
  status: string;
  paidAt: string | null;
  createdAt: string;
}

/** Paginated page shape — wraps summaries + opaque cursor. */
export interface PaymentPage {
  items: PaymentSummaryView[];
  nextCursor: string | null;
}
